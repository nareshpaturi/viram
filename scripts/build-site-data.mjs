// Writes site/r/library.js: the installed library's names and step structure,
// so the viram.app fallback page validates links with the app's own rules.
// Run with `npm run site:data`; `--check` verifies it is current (CI).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { LIBRARY } from '../src/content/library.ts';

const OUTPUT = 'site/r/library.js';
const techniques = Object.fromEntries(
  LIBRARY.filter((t) => t.shareable && t.riskTier === 'gentle').map((t) => [
    t.id,
    {
      name: t.name,
      subtitle: t.subtitle,
      increment: t.practice.increment,
      steps: t.practice.steps.map((s) => ({ kind: s.kind, ...(s.side ? { side: s.side } : {}), ...(s.cue ? { cue: s.cue } : {}) })),
    },
  ]),
);
const source = `// Generated by scripts/build-site-data.mjs from src/content/library.ts. Do not edit.
export const TECHNIQUES = ${JSON.stringify(techniques, null, 2)};
`;

if (process.argv.includes('--check')) {
  if (!existsSync(OUTPUT) || readFileSync(OUTPUT, 'utf8') !== source) {
    console.error(`${OUTPUT} is out of date. Run npm run site:data.`);
    process.exit(1);
  }
  console.log('Site library data is current.');
} else {
  writeFileSync(OUTPUT, source);
  console.log(`Wrote ${OUTPUT}.`);
}
